import { readFileSync } from "node:fs";
import path from "node:path";

import type { DocType } from "./constants";
import { DocsError } from "./errors";
import { state } from "./state";
import { relpath, splitFrontMatter } from "./util";

export function substitute(
  text: string,
  values: Record<string, string>,
): string {
  return text.replace(
    /\{\{\s*([A-Za-z0-9_]+)\s*\}\}/g,
    (match, key: string) => values[key.trim()] ?? match,
  );
}

export function templateBody(
  docType: DocType,
  values: Record<string, string>,
): string {
  const file = path.join(state.templates, `${docType}.md`);
  let text: string;
  try {
    text = readFileSync(file, "utf8");
  } catch (error) {
    throw new DocsError(`cannot read ${relpath(file)}: ${(error as Error).message}`);
  }
  const { body } = splitFrontMatter(text);
  return substitute(body, values);
}

export function ensureRecordSections(
  body: string,
  commits: readonly string[],
): string {
  const hasCommit = /^#{2,6}\s*.*\bcommit/im.test(body);
  const hasEvidence = /^#{2,6}\s*.*\b(?:evidence|verification|validation)/im.test(
    body,
  );
  const appended: string[] = [];
  if (!hasCommit) {
    const value = commits.length > 0 ? commits.join(", ") : "TBD";
    appended.push(`## Commits\n\n\`${value}\``);
  }
  if (!hasEvidence) {
    appended.push("## Evidence\n\n- TODO");
  }
  if (appended.length === 0) {
    return body;
  }
  const prefix = body.replace(/\n+$/g, "");
  const suffix = appended.join("\n\n");
  return prefix ? `${prefix}\n\n${suffix}\n` : `${suffix}\n`;
}

export function defaultSpecialFields(
  docType: DocType,
): Record<string, unknown> {
  switch (docType) {
    case "design":
      return {
        parent: null,
        scope: "TODO: one-sentence boundary",
        owns: [],
        does_not_own: [],
        interfaces: [],
        implementation: "none",
      };
    case "proposal":
      return { issue: null, design: null, activation_trigger: null };
    case "decision":
      return { options: [], decision: "TODO", consequences: [] };
    case "record":
      return { commits: [], proposal: null, evidence: [] };
    case "report":
      return { method: "TODO", findings: [], limitations: [] };
    case "reference":
      return { read_when: [] };
  }
}

export function splitValues(value?: string | null): string[] {
  if (!value) {
    return [];
  }
  const result: string[] = [];
  for (const item of value.split(",")) {
    const trimmed = item.trim();
    if (trimmed && !result.includes(trimmed)) {
      result.push(trimmed);
    }
  }
  return result;
}

