/** Generated docs README; `version` is the package version the root follows. */
export function initReadme(version: string): string {
  return `# Documentation

> This directory follows the engineering-docs standard. Project metadata is in [project.yaml](project.yaml);
> read the standard with \`npx @jk-97/engineering-docs@${version} standard\`;
> indexes are generated by the pinned CLI, not by files inside this directory.

## Types

| Directory | Content |
| --- | --- |
| [designs/](designs/) | current system state, boundaries, and interfaces |
| [proposals/](proposals/) | future changes and implementation plans |
| [decisions/](decisions/) | accepted architecture trade-offs |
| [records/](records/) | implemented changes and evidence |
| [reports/](reports/) | investigations, measurements, and validation |
| [references/](references/) | read-only snapshots of external material |
| [assets/](assets/) | images and data attachments |

## Entry

- System overview: [designs/system-overview.md](designs/system-overview.md)

## Workflow

1. Idea: defects, tasks, and one-line ideas go to a GitHub Issue; a detailed future idea becomes a \`status: deferred\` proposal.
2. Plan: write a proposal when a design change is needed, with the implementation plan and verification inside it.
3. Implement: merge the PR and update the target design in the same change.
4. Record: write a record for cross-component, risky, or incident work; small changes only update the design.
5. Close: set the proposal to \`implemented\`, close the Issue, and run \`index\` and \`check\`.

Any harness (OpenCode, Codex, Claude Code, etc.) reads this directory, the installed project-docs skill, and the repository \`AGENTS.md\`.

## Conventions

- Work items, defects, and scheduling go to GitHub Issues; implementation plans go to proposals.
- Run the commands below from the repository root; \`--root docs\` selects this docs root.
- Create documents with \`npx @jk-97/engineering-docs@${version} --root docs new --type <type> --status <status> --title "<title>"\`.
- Validate with \`npx @jk-97/engineering-docs@${version} --root docs index --check\` and \`npx @jk-97/engineering-docs@${version} --root docs check\`.
`;
}

